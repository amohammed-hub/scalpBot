// Helper: verify admin access via cookie (checks role, mobile, and ADMIN_MOBILE)
async function verifyAdminAccess(ctx: any): Promise<boolean> {
  const authToken: string | undefined = ctx.req?.cookies?.scalpbot_auth
    || ctx.req?.headers?.authorization?.replace("Bearer ", "")
    || (ctx.req?.headers?.["x-auth-token"] as string | undefined);
  if (authToken) {
    try {
      const decoded = jwt.verify(authToken, process.env.JWT_SECRET || "fallback-secret") as { userId?: number; role?: string; mobile?: string };
      if (decoded.role === "admin" || decoded.mobile === ENV.adminMobile) return true;
      // Check DB for current role (handles JWT issued before promotion)
      if (decoded.userId) {
        const user = await getAppUserById(decoded.userId);
        if (user?.role === "admin" || user?.mobile === ENV.adminMobile) return true;
      }
    } catch {}
  }
  // Legacy admin cookie
  const adminToken = ctx.req?.cookies?.scalpbot_admin;
  if (adminToken) {
    try {
      const decoded = jwt.verify(adminToken, process.env.JWT_SECRET || "fallback-secret") as { isAdmin?: boolean };
      if (decoded.isAdmin) return true;
    } catch {}
  }
  return false;
}

// Helper: verify session ownership — checks JWT cookie belongs to the user who owns the sessionToken (or is admin)
async function verifySessionOwnership(ctx: any, inputSessionToken: string): Promise<void> {
  const authToken: string | undefined = ctx.req?.cookies?.scalpbot_auth
    || ctx.req?.headers?.authorization?.replace("Bearer ", "")
    || (ctx.req?.headers?.["x-auth-token"] as string | undefined);
  if (!authToken) {
    throw new Error("Unauthorized: no auth token");
  }
  let decoded: { userId?: number; role?: string; mobile?: string };
  try {
    decoded = jwt.verify(authToken, process.env.JWT_SECRET || "fallback-secret") as any;
  } catch {
    throw new Error("Unauthorized: invalid auth token");
  }
  // Admin can control any session
  if (decoded.role === "admin" || decoded.mobile === ENV.adminMobile) return;
  // Check user's sessionToken matches the input (strip slot suffix for secondary bots)
  const baseToken = inputSessionToken.replace(/-slot[0-9]+$/, "");
  if (decoded.userId) {
    const user = await getAppUserById(decoded.userId);
    if (user?.sessionToken === baseToken) return;
    if (user?.role === "admin" || user?.mobile === ENV.adminMobile) return;
  }
  throw new Error("Unauthorized: session does not belong to you");
}

// ── IP PROTECTION: Strip strategy details from non-admin API responses ──────────
// Admin (owner) sees everything. Regular users only see: trade entry, exit, P&L, direction.
// They do NOT see: strategy layer name, confidence %, signal reason, candle data.
async function isAdminSessionToken(sessionToken: string): Promise<boolean> {
  if (!ENV.adminMobile) return false;
  const db = await getDb();
  if (!db) return false;
  try {
    const baseToken = sessionToken.replace(/-slot[0-9]+$/, "");
    const [rows]: any = await db.execute(sql`SELECT role, mobile FROM app_users WHERE sessionToken = ${baseToken} LIMIT 1`);
    const row = Array.isArray(rows) ? rows[0] : rows;
    if (!row) return false;
    return row.role === "admin" || row.mobile === ENV.adminMobile;
  } catch { return false; }
}

function stripSignalForUser(signal: any): any {
  if (!signal) return signal;
  return {
    direction: signal.direction,
    entryPrice: signal.entryPrice,
    slPrice: signal.slPrice,
    targetPrice: signal.targetPrice,
    atr: signal.atr,
    reason: signal.direction === "HOLD" ? "Scanning..." : "Signal active",
    layer: "None",
    confidence: 0,
  };
}

function stripOpenTradeForUser(trade: any): any {
  if (!trade) return trade;
  return { ...trade, signalReason: undefined, signalLayer: undefined, confidence: 0 };
}
